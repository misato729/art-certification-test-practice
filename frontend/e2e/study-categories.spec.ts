import { test, expect } from '@playwright/test'

const base = { subtitle: null, source_page: null, reference_page: null, scheme: 'study_outline' }
const child = (code: string, parent_code: string, label: string, number: number) => ({ ...base, code, parent_code, label, number, sort_order: number, children: [] })
const part = (code: string, label: string, number: number, children: ReturnType<typeof child>[]) => ({ ...base, code, parent_code: null, label, number, sort_order: number, children })
const western = part('part_01', '西洋美術史', 1, [child('part_01_section_01', 'part_01', '合成の西洋分類1', 1), child('part_01_section_02', 'part_01', '合成の西洋分類2', 2)])
const japanese = part('part_02', '日本美術史', 2, [child('part_02_section_01', 'part_02', '合成の日本分類1', 1), child('part_02_section_02', 'part_02', '合成の日本分類2', 2)])
const other = part('part_04', 'その他のジャンル', 4, [child('part_04_section_01', 'part_04', '東洋美術', 1), child('part_04_section_02', 'part_04', '合成の工芸分類', 2), child('part_04_section_03', 'part_04', '合成の展覧会分類', 3)])

test('exam presets select the exact genre children, combine independently, and clear to all questions', async ({ page }) => {
  await page.route('**/api/v1/study_categories', route => route.fulfill({ json: { data: { study_outline: [western, japanese, other], exam_scope: [] } } }))
  await page.goto('/')
  await page.getByRole('tab', { name: '条件を指定', exact: true }).click()
  const count = page.locator('.condition-submit strong')
  const start = page.getByRole('button', { name: '順番に始める', exact: true })
  const world = page.getByRole('checkbox', { name: '受験世界史', exact: true })
  const japan = page.getByRole('checkbox', { name: '受験日本史', exact: true })
  const east = page.getByRole('checkbox', { name: '東洋美術', exact: true })
  const genreParent = (name: string) => page.getByRole('checkbox', { name, exact: true })
  const checkedChildren = () => page.locator('input[name="study-category-codes"]:checked')
  await expect(page.locator('legend').filter({ hasText: /^出題ジャンル$/ })).toHaveCount(1)
  await expect(page.locator('legend').filter({ hasText: /^分野$/ })).toHaveCount(0)
  await expect(count).toHaveText('全85問')

  await world.check()
  await expect(genreParent(western.label)).toBeChecked()
  await expect(genreParent(japanese.label)).not.toBeChecked()
  await expect(genreParent(other.label)).toBeChecked({ indeterminate: true })
  await expect(east).toBeChecked()
  await expect(page.getByRole('checkbox', { name: '合成の工芸分類', exact: true })).not.toBeChecked()
  await expect(page.getByRole('checkbox', { name: '合成の展覧会分類', exact: true })).not.toBeChecked()
  await expect(checkedChildren()).toHaveCount(3)
  await expect(count).toHaveText('全0問')
  await expect(start).toBeDisabled()
  await expect(page.getByRole('status').filter({ hasText: 'この条件に合う公開問題はまだありません' })).toBeVisible()

  await page.getByRole('checkbox', { name: '合成の日本分類1', exact: true }).check()
  await expect(world).toBeChecked({ indeterminate: true })
  await world.check()
  await expect(checkedChildren()).toHaveCount(3)
  await expect(world).toBeChecked()
  await japan.check()
  await expect(world).toBeChecked()
  await expect(japan).toBeChecked()
  await expect(genreParent(japanese.label)).toBeChecked()
  await expect(checkedChildren()).toHaveCount(5)
  await world.uncheck()
  await expect(japan).toBeChecked()
  await expect(checkedChildren()).toHaveCount(2)
  await expect(east).not.toBeChecked()

  await page.getByRole('button', { name: '絞り込みを解除', exact: true }).click()
  await expect(checkedChildren()).toHaveCount(0)
  await expect(count).toHaveText('全85問')
  await expect(start).toBeEnabled()
  await genreParent(other.label).check()
  await expect(checkedChildren()).toHaveCount(3)
  await world.check()
  await expect(checkedChildren()).toHaveCount(3)
  await expect(genreParent(western.label)).toBeChecked()
  await expect(east).toBeChecked()
  await expect(page.getByRole('checkbox', { name: '合成の工芸分類', exact: true })).not.toBeChecked()
  await expect(page.getByRole('checkbox', { name: '合成の展覧会分類', exact: true })).not.toBeChecked()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('a classified URL never discards its filter and renders an unrelated question', async ({ page }) => {
  const response = page.waitForResponse(response => {
    const url = new URL(response.url())
    return url.pathname === '/api/v1/questions/next' && url.searchParams.get('study_category_codes') === 'part_01_section_01'
  })
  await page.goto('/practice/1/1?study_category_codes=part_01_section_01')
  expect([400, 404]).toContain((await response).status())
  await expect(page.getByRole('heading', { name: '問題を表示できません', exact: true })).toBeVisible()
  await expect(page.getByRole('radio')).toHaveCount(0)
})
